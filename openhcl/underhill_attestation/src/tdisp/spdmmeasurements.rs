/// SPDM GET_MEASUREMENTS request message
#[derive(Debug, KnownLayout, FromBytes, Immutable)]
#[repr(C)]
pub struct SpdmMeasurementRequestMessage {
    /// SPDM protocol version
    pub spdm_version: u8,
    /// Request/response code
    pub request_response_code: u8,
    /// Parameter 1: attributes
    pub param1: u8,
    /// Parameter 2: measurement operation
    pub param2: u8,
    /// Random nonce for freshness
    pub nonce: [u8; 32],
    /// Slot ID parameter
    pub slot_id_param: u8,
}

static_assertions::const_assert_eq!(size_of::<SpdmMeasurementRequestMessage>(), 37);

impl TryFrom<&[u8]> for SpdmMeasurementRequestMessage {
    type Error = MeasurementError;

    fn try_from(data: &[u8]) -> Result<Self, Self::Error> {
        if data.len() < size_of::<Self>() {
            return Err(MeasurementError::SizeMismatch {
                expected: size_of::<Self>(),
                actual: data.len(),
            });
        }

        match Self::read_from_prefix(data) {
            Ok((req, _)) => Ok(req),
            Err(_) => Err(MeasurementError::InvalidHexString(
                "Failed to parse SPDM measurement request".to_string(),
            )),
        }
    }
}

#[derive(Debug, KnownLayout, FromBytes, Immutable)]
#[repr(C, packed)]
struct DmtfMeasurementSerialized {
    pub dmtf_spec_measurement_value_type: u8,
    pub dmtf_spec_measurement_value_size: u16,
}

static_assertions::const_assert_eq!(size_of::<DmtfMeasurementSerialized>(), 3);

/// Representation type for DMTF measurement values (bit 7 of value_type)
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum MeasurementRepresentation {
    /// Digest representation (bit 7 = 0)
    Digest = 0,
    /// Raw bit stream representation (bit 7 = 1)
    /// The Responder should ensure the raw bit stream does not contain secrets
    RawBitStream = 1,
}

impl From<bool> for MeasurementRepresentation {
    fn from(raw: bool) -> Self {
        if raw {
            MeasurementRepresentation::RawBitStream
        } else {
            MeasurementRepresentation::Digest
        }
    }
}

impl From<MeasurementRepresentation> for bool {
    fn from(repr: MeasurementRepresentation) -> Self {
        match repr {
            MeasurementRepresentation::Digest => false,
            MeasurementRepresentation::RawBitStream => true,
        }
    }
}

/// What is being measured by DMTF measurement value (bits 6:0 of value_type)
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum MeasurementType {
    /// Immutable ROM
    ImmutableRom = 0x00,
    /// Mutable firmware
    MutableFirmware = 0x01,
    /// Hardware configuration, such as straps
    HardwareConfiguration = 0x02,
    /// Firmware configuration, such as configurable firmware policy
    FirmwareConfiguration = 0x03,
    /// Measurement manifest
    /// The Responder should support setting representation to either Digest or RawBitStream
    MeasurementManifest = 0x04,
    /// Structured representation of debug and device mode
    /// Representation shall be set to RawBitStream
    DebugAndDeviceMode = 0x05,
    /// Mutable firmware's version number
    /// This specification does not mandate a format for firmware version number
    /// Representation should be set to RawBitStream
    FirmwareVersionNumber = 0x06,
    /// Mutable firmware's security version number
    /// Should be formatted as an 8-byte unsigned integer
    /// Representation should be set to RawBitStream
    FirmwareSecurityVersionNumber = 0x07,
}

impl TryFrom<u8> for MeasurementType {
    type Error = MeasurementError;

    fn try_from(value: u8) -> Result<Self, Self::Error> {
        match value & 0x7F {
            0x00 => Ok(MeasurementType::ImmutableRom),
            0x01 => Ok(MeasurementType::MutableFirmware),
            0x02 => Ok(MeasurementType::HardwareConfiguration),
            0x03 => Ok(MeasurementType::FirmwareConfiguration),
            0x04 => Ok(MeasurementType::MeasurementManifest),
            0x05 => Ok(MeasurementType::DebugAndDeviceMode),
            0x06 => Ok(MeasurementType::FirmwareVersionNumber),
            0x07 => Ok(MeasurementType::FirmwareSecurityVersionNumber),
            _ => Err(MeasurementError::InvalidHexString(format!(
                "Reserved measurement type: 0x{:02x}",
                value & 0x7F
            ))),
        }
    }
}

/// Parsed DMTF measurement value type combining representation and measurement type
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DmtfMeasurementValueType {
    /// How the measurement is represented (digest or raw value)
    pub representation: MeasurementRepresentation,
    /// Type of measurement being represented
    pub measurement_type: MeasurementType,
}

impl From<DmtfMeasurementValueType> for u8 {
    fn from(value_type: DmtfMeasurementValueType) -> Self {
        let repr_bit = if bool::from(value_type.representation) {
            0x80
        } else {
            0x00
        };
        let type_bits = value_type.measurement_type as u8;
        repr_bit | type_bits
    }
}

impl TryFrom<u8> for DmtfMeasurementValueType {
    type Error = MeasurementError;

    fn try_from(value: u8) -> Result<Self, Self::Error> {
        let representation = MeasurementRepresentation::from((value & 0x80) != 0);
        let measurement_type = MeasurementType::try_from(value & 0x7F)?;

        Ok(DmtfMeasurementValueType {
            representation,
            measurement_type,
        })
    }
}

impl fmt::Display for DmtfMeasurementValueType {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{:?}({:?})", self.measurement_type, self.representation)
    }
}

/// DMTF-format measurement data
#[derive(Debug)]
pub struct DmtfMeasurement {
    /// Type of measurement value
    pub value_type: DmtfMeasurementValueType,
    /// Size of the measurement value in bytes
    pub value_size: u16,
    /// The measurement value data
    pub value: Vec<u8>,
}

impl TryFrom<&[u8]> for DmtfMeasurement {
    type Error = MeasurementError;

    fn try_from(data: &[u8]) -> Result<Self, Self::Error> {
        if data.len() < size_of::<DmtfMeasurementSerialized>() {
            return Err(MeasurementError::SizeMismatch {
                expected: size_of::<DmtfMeasurementSerialized>(),
                actual: data.len(),
            });
        }

        let header = match DmtfMeasurementSerialized::read_from_prefix(data) {
            Ok((header, _)) => header,
            Err(_) => {
                return Err(MeasurementError::InvalidHexString(
                    "Failed to parse DMTF measurement header".to_string(),
                ));
            }
        };

        let value_type =
            DmtfMeasurementValueType::try_from(header.dmtf_spec_measurement_value_type)?;

        let value_start = size_of::<DmtfMeasurementSerialized>();
        let value_end = value_start + header.dmtf_spec_measurement_value_size as usize;

        if data.len() < value_end {
            return Err(MeasurementError::SizeMismatch {
                expected: value_end,
                actual: data.len(),
            });
        }

        Ok(DmtfMeasurement {
            value_type,
            value_size: header.dmtf_spec_measurement_value_size,
            value: data[value_start..value_end].to_vec(),
        })
    }
}

impl fmt::Display for DmtfMeasurement {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "DmtfMeasurement {{ type: {}, size: {}, value: {} }}",
            self.value_type,
            self.value_size,
            hex::encode(&self.value)
        )
    }
}

/// A single measurement record with an index
#[derive(Debug)]
pub struct MeasurementRecord {
    /// Measurement index
    pub index: u8,
    /// The measurement data
    pub measurement: DmtfMeasurement,
}

impl TryFrom<&[u8]> for MeasurementRecord {
    type Error = MeasurementError;

    fn try_from(data: &[u8]) -> Result<Self, Self::Error> {
        // SPDM measurement block format:
        // Index (1 byte) + MeasurementSpecification (1 byte) + MeasurementSize (2 bytes) + Measurement

        if data.len() < 4 {
            return Err(MeasurementError::SizeMismatch {
                expected: 4,
                actual: data.len(),
            });
        }

        let index = data[0];
        let measurement_spec = data[1];
        let measurement_size = u16::from_le_bytes([data[2], data[3]]);

        // Validate that we have enough data for the measurement
        if data.len() < 4 + measurement_size as usize {
            return Err(MeasurementError::SizeMismatch {
                expected: 4 + measurement_size as usize,
                actual: data.len(),
            });
        }

        // For DMTF specification (measurement_spec = 1), parse as DMTF measurement
        if measurement_spec == 1 {
            let measurement_data = &data[4..4 + measurement_size as usize];
            let measurement = DmtfMeasurement::try_from(measurement_data)?;

            Ok(MeasurementRecord { index, measurement })
        } else {
            Err(MeasurementError::InvalidHexString(format!(
                "Unsupported measurement specification: {}",
                measurement_spec
            )))
        }
    }
}

impl fmt::Display for MeasurementRecord {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "MeasurementRecord {{ index: {}, measurement: {} }}",
            self.index, self.measurement
        )
    }
}

/// Opaque data that may be included in SPDM responses
#[derive(Debug)]
pub struct OpaqueData {
    /// The opaque data bytes
    pub data: Vec<u8>,
}

#[derive(Debug, KnownLayout, FromBytes, Immutable)]
#[repr(C)]
struct SpdmMeasurementResponseSerialized {
    pub spdm_version: u8,
    pub request_response_code: u8,
    pub param1: u8,
    pub param2: u8,
    pub number_of_blocks: u8,
    pub measurement_record_length: [u8; 3], // 24-bit little endian
}

static_assertions::const_assert_eq!(size_of::<SpdmMeasurementResponseSerialized>(), 8);

/// Helper to convert 3-byte little-endian array to u32
fn read_u24_le(bytes: &[u8; 3]) -> u32 {
    u32::from_le_bytes([bytes[0], bytes[1], bytes[2], 0])
}

/// SPDM GET_MEASUREMENTS response message
#[derive(Debug)]
pub struct SpdmMeasurementResponseMessage {
    /// SPDM protocol version
    pub spdm_version: u8,
    /// Request/response code
    pub request_response_code: u8,
    /// Parameter 1: number of measurements
    pub param1: u8,
    /// Parameter 2: slot ID
    pub param2: u8,
    /// Number of measurement blocks
    pub number_of_blocks: u8,
    /// Total length of measurement records
    pub measurement_record_length: u32,
    /// The measurement records
    pub measurement_records: Vec<MeasurementRecord>,
    /// Optional nonce for freshness
    pub nonce: Option<[u8; 32]>,
    /// Optional opaque data
    pub opaque_data: Option<OpaqueData>,
    /// Optional signature over the measurements
    pub signature: Option<Vec<u8>>,
}

impl TryFrom<&[u8]> for SpdmMeasurementResponseMessage {
    type Error = MeasurementError;

    fn try_from(data: &[u8]) -> Result<Self, Self::Error> {
        if data.len() < size_of::<SpdmMeasurementResponseSerialized>() {
            return Err(MeasurementError::SizeMismatch {
                expected: size_of::<SpdmMeasurementResponseSerialized>(),
                actual: data.len(),
            });
        }

        let header = match SpdmMeasurementResponseSerialized::read_from_prefix(data) {
            Ok((header, _)) => header,
            Err(_) => {
                return Err(MeasurementError::InvalidHexString(
                    "Failed to parse SPDM measurement response header".to_string(),
                ));
            }
        };

        let measurement_record_length = read_u24_le(&header.measurement_record_length);
        let mut offset = size_of::<SpdmMeasurementResponseSerialized>();

        // Parse measurement records
        let mut measurement_records = Vec::new();
        let records_end = offset + measurement_record_length as usize;

        if data.len() < records_end {
            return Err(MeasurementError::SizeMismatch {
                expected: records_end,
                actual: data.len(),
            });
        }

        while offset < records_end {
            let remaining_data = &data[offset..records_end];
            let record = MeasurementRecord::try_from(remaining_data)?;

            // Calculate the size of this record to advance offset
            let record_size =
                4 + record.measurement.value_size as usize + size_of::<DmtfMeasurementSerialized>();
            offset += record_size;

            measurement_records.push(record);
        }

        offset = records_end;

        // Parse optional fields based on param1 flags
        let mut nonce = None;
        let opaque_data = None;
        let signature = None;

        // Check for nonce (bit 0 of param1)
        if header.param1 & 0x01 != 0 {
            if data.len() < offset + 32 {
                return Err(MeasurementError::SizeMismatch {
                    expected: offset + 32,
                    actual: data.len(),
                });
            }
            let mut nonce_bytes = [0u8; 32];
            nonce_bytes.copy_from_slice(&data[offset..offset + 32]);
            nonce = Some(nonce_bytes);
            // offset += 32; // Not needed - we skip opaque data and signature parsing
        }

        // For simplicity, we'll skip opaque data and signature parsing for now
        // These would require additional length fields and more complex parsing

        Ok(SpdmMeasurementResponseMessage {
            spdm_version: header.spdm_version,
            request_response_code: header.request_response_code,
            param1: header.param1,
            param2: header.param2,
            number_of_blocks: header.number_of_blocks,
            measurement_record_length,
            measurement_records,
            nonce,
            opaque_data,
            signature,
        })
    }
}

impl fmt::Display for SpdmMeasurementResponseMessage {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        writeln!(f, "SpdmMeasurementResponseMessage {{")?;
        writeln!(f, "  version: 0x{:02x}", self.spdm_version)?;
        writeln!(f, "  response_code: 0x{:02x}", self.request_response_code)?;
        writeln!(f, "  param1: 0x{:02x}", self.param1)?;
        writeln!(f, "  param2: 0x{:02x}", self.param2)?;
        writeln!(f, "  number_of_blocks: {}", self.number_of_blocks)?;
        writeln!(
            f,
            "  measurement_record_length: {}",
            self.measurement_record_length
        )?;
        for (i, record) in self.measurement_records.iter().enumerate() {
            writeln!(f, "  record[{}]: {}", i, record)?;
        }
        write!(f, "}}")
    }
}

